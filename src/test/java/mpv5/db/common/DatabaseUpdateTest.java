package mpv5.db.common;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;
import java.util.TreeMap;
import mpv5.globals.Constants;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * Schema updates and the rebuild of damaged databases, with an embedded
 * Derby database
 */
class DatabaseUpdateTest {

    @TempDir
    Path tmp;
    private File db;

    @AfterEach
    void shutdown() {
        if (db != null) {
            DerbyRebuild.shutdown(db);
        }
    }

    /**
     * like {@link DatabaseInstallation#INITIAL_DATA}, without UI dependencies
     */
    private static final String[] INITIAL = {
        "INSERT INTO groups (cname, description, dateadded) VALUES ('Alle', 'all', '2009-04-03')",
        "INSERT INTO accounts (cname, description, dateadded, taxvalue, intaccounttype, frame, intprofitfid, inttaxfid, inttaxuid)"
        + " VALUES ('Konten', '', '2009-04-03', 0.0, 0, 'builtin', 0, 0, 0)",
        "INSERT INTO users (fullname, password, cname, laf, locale, mail, language, inthighestright, datelastlog, isenabled, dateadded)"
        + " VALUES ('Administrator', 'x', 'admin', '', 'de_DE', '', 'buildin_en', 0, '2009-04-03', 1, '2009-04-03')",
        "INSERT INTO globalsettings (cname, groupsids, value) VALUES ('yabs_dbversion', 1, '1.0')"
    };

    private Connection create() throws SQLException {
        db = tmp.resolve("yabs").toFile();
        Connection c = DriverManager.getConnection("jdbc:derby:" + db.getPath() + ";create=true");
        new SchemaUpdate(r -> c, true, null).runAll(DatabaseInstallation.DERBY_STRUCTURE);
        exec(c, INITIAL);
        return c;
    }

    private static Connection open(File db) throws SQLException {
        return DriverManager.getConnection("jdbc:derby:" + db.getPath());
    }

    private static void exec(Connection c, String... sql) throws SQLException {
        try (Statement s = c.createStatement()) {
            for (String q : sql) {
                s.execute(q);
            }
        }
    }

    private static String query(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            return rs.next() && rs.getString(1) != null ? rs.getString(1).trim() : null;
        }
    }

    private static Map<Double, String[]> derbyUpdates() {
        return new DatabaseUpdater().getStructureForMigration(ConnectionTypeHandler.DERBY);
    }

    @Test
    void newDatabaseIsUpdatedToCurrentVersion() throws Exception {
        try (Connection c = create()) {
            double v = new SchemaUpdate(r -> c, true, null).run(1.0, derbyUpdates());
            assertEquals(Constants.DATABASE_VERSION, v, 0.00001);
            assertEquals(String.valueOf(Constants.DATABASE_VERSION), query(c, "SELECT value FROM globalsettings WHERE cname = 'yabs_dbversion'"));
            //the columns of the updates exist
            exec(c, "SELECT payterm FROM contacts", "SELECT discountgrosvalue, reforderids FROM items", "SELECT eventtype FROM schedule",
                    "SELECT itemsids, txnumber, sigcounter, signature, tseserial, processdata, tsefailed FROM postransactions");
        }
    }

    @Test
    void partlyAppliedUpdatesContinue() throws Exception {
        //like the reported database: version 1.1974, but changes of later updates exist
        try (Connection c = create()) {
            Map<Double, String[]> upTo = new TreeMap<Double, String[]>(derbyUpdates().entrySet().stream()
                    .filter(e -> e.getKey() <= 1.1974)
                    .collect(java.util.stream.Collectors.toMap(Map.Entry::getKey, Map.Entry::getValue)));
            new SchemaUpdate(r -> c, true, null).run(1.0, upTo);
            assertEquals("1.1974", query(c, "SELECT value FROM globalsettings WHERE cname = 'yabs_dbversion'"));
            exec(c, "ALTER TABLE schedule ADD COLUMN eventtype2 BIGINT",
                    "CREATE TABLE fontsforitext (IDS BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY, cname VARCHAR(250) NOT NULL, PRIMARY KEY (ids))",
                    "ALTER TABLE activitylists ADD COLUMN isbilled SMALLINT DEFAULT 0");

            double v = new SchemaUpdate(r -> c, true, null).run(1.1974, derbyUpdates());
            assertEquals(Constants.DATABASE_VERSION, v, 0.00001);
            exec(c, "SELECT eventtype FROM schedule", "SELECT encoding, font FROM fontsforitext", "SELECT payterm FROM contacts");
        }
    }

    @Test
    void failedUpdateKeepsTheLastGoodVersion() throws Exception {
        try (Connection c = create()) {
            Map<Double, String[]> updates = new TreeMap<Double, String[]>();
            updates.put(1.5, new String[]{"CREATE TABLE test1 (a INT)"});
            updates.put(1.6, new String[]{"CREATE TABLE test2 (a INT)", "INSERT INTO test2 (a) VALUES ('kein int')"});
            updates.put(1.7, new String[]{"CREATE TABLE test3 (a INT)"});
            SchemaUpdate.UpdateException e = assertThrows(SchemaUpdate.UpdateException.class,
                    () -> new SchemaUpdate(r -> c, true, null).run(1.0, updates));
            assertEquals(1.6, e.getVersion(), 0.00001);
            assertFalse(e instanceof SchemaUpdate.DamagedDatabaseException);
            assertEquals("1.5", query(c, "SELECT value FROM globalsettings WHERE cname = 'yabs_dbversion'"));
            assertThrows(SQLException.class, () -> exec(c, "SELECT * FROM test3"), "1.7 must not run");
        }
    }

    @Test
    void reconnectsWhenTheConnectionWasClosed() throws Exception {
        try (Connection c = create()) {
            Connection[] current = {c};
            Map<Double, String[]> updates = new TreeMap<Double, String[]>();
            updates.put(1.5, new String[]{"CREATE TABLE test1 (a INT)"});
            c.close();
            double v = new SchemaUpdate(r -> {
                if (r) {
                    current[0] = open(db);
                }
                return current[0];
            }, true, null).run(1.0, updates);
            assertEquals(1.5, v, 0.00001);
            current[0].close();
        }
    }

    @Test
    void updateDoesNotRequestGeneratedKeys() throws Exception {
        //Derby 10.17 closes the connection on UPDATE userproperties with RETURN_GENERATED_KEYS
        //(ArrayIndexOutOfBoundsException) - "no current connection" when YaBS is closed
        assertEquals(Statement.RETURN_GENERATED_KEYS, DatabaseConnection.generatedKeys(" insert INTO items (cname) VALUES ('a')"));
        assertEquals(Statement.NO_GENERATED_KEYS, DatabaseConnection.generatedKeys("UPDATE userproperties SET value = 'a'"));
        assertEquals(Statement.NO_GENERATED_KEYS, DatabaseConnection.generatedKeys("DELETE FROM objectlocks WHERE ids = 1"));
        assertEquals(Statement.NO_GENERATED_KEYS, DatabaseConnection.generatedKeys(null));
        try (Connection c = create()) {
            new SchemaUpdate(r -> c, true, null).run(1.0, derbyUpdates());
            String update = "UPDATE userproperties SET value = 'a', dateadded = '2026-11-07' WHERE usersids = 1 AND cname = 'x'";
            try (Statement s = c.createStatement()) {
                s.executeUpdate(update, DatabaseConnection.generatedKeys(update));
            }
            assertFalse(c.isClosed());
        }
    }

    @Test
    void classifiesDerbyErrors() {
        assertEquals(SchemaUpdate.Outcome.DAMAGED, SchemaUpdate.classify(
                new SQLException("StoredPreparedStatement '58f10349-012e-4f2f-1cb2-0000019e4c10' ist nicht vorhanden.", "42X94"), true));
        assertEquals(SchemaUpdate.Outcome.DAMAGED, SchemaUpdate.classify(
                new SQLException("Java-Ausnahme: 'NullPointerException'", "XJ001"), true));
        assertEquals(SchemaUpdate.Outcome.ALREADY_DONE, SchemaUpdate.classify(
                new SQLException("Column 'EVENTTYPE2' ist bereits vorhanden.", "X0Y32"), true));
        assertEquals(SchemaUpdate.Outcome.ALREADY_DONE, SchemaUpdate.classify(
                new SQLException("'PATH' ist keine Spalte", "42X14"), true));
        assertEquals(SchemaUpdate.Outcome.CONNECTION_LOST, SchemaUpdate.classify(
                new SQLException("Keine aktuelle Verbindung.", "08003"), true));
        assertEquals(SchemaUpdate.Outcome.FAILED, SchemaUpdate.classify(
                new SQLException("Syntax error", "42X01"), true));
        assertEquals(SchemaUpdate.Outcome.ALREADY_DONE, SchemaUpdate.classify(
                new SQLException("Duplicate column name", "42S21", 1060), false));
    }

    @Test
    void rebuildCopiesAllData() throws Exception {
        long[] counts;
        String[] tables = {"GROUPS", "CONTACTS", "ITEMS", "REVENUES", "FILES", "PRODUCTORDERS", "SEARCHINDEX", "GLOBALSETTINGS"};
        try (Connection c = create()) {
            new SchemaUpdate(r -> c, true, null).run(1.0, derbyUpdates());
            //a subgroup with a higher id referenced by a group created before
            exec(c, "INSERT INTO groups (ids, cname, description, dateadded, groupsids) VALUES (7, 'Sub', '', '2020-01-01', 1)",
                    "INSERT INTO groups (ids, cname, description, dateadded, groupsids) VALUES (5, 'SubSub', '', '2020-01-01', 7)");
            for (int i = 1; i <= 120; i++) {
                exec(c, "INSERT INTO contacts (cnumber, cname, dateadded, groupsids) VALUES ('K" + i + "', 'Kunde " + i + "', '2020-01-01', 1)",
                        "INSERT INTO items (cname, cnumber, dateadded, contactsids, netvalue) VALUES ('R" + i + "', 'R" + i + "', '2020-01-01', " + i + ", " + i + ".5)",
                        "INSERT INTO revenues (cname, dateadded, netvalue) VALUES ('E" + i + "', '2020-01-01', " + i + ")");
            }
            exec(c, "DELETE FROM items WHERE ids = 3",
                    "INSERT INTO items (cname, cnumber, dateadded, contactsids, reforderids) VALUES ('Gutschrift', 'G1', '2020-01-01', 1, 2)",
                    "INSERT INTO productorders (cname, cnumber, dateadded, contactsids) VALUES ('B1', 'B1', '2020-01-01', 1)",
                    "INSERT INTO productorders (cname, cnumber, dateadded, contactsids) VALUES ('B2', 'B2', '2020-01-01', 2)",
                    "DELETE FROM productorders WHERE cname = 'B1'");
            try (java.sql.PreparedStatement p = c.prepareStatement("INSERT INTO files (cname, dateadded, data, filesize) VALUES ('f1', '2020-01-01', ?, 3)")) {
                p.setBytes(1, new byte[]{1, 2, 3});
                p.executeUpdate();
            }
            counts = counts(c, tables);
        }
        DerbyRebuild.shutdown(db);

        DerbyRebuild rebuild = new DerbyRebuild(db, null, null, DatabaseInstallation.DERBY_STRUCTURE, INITIAL, derbyUpdates(), null);
        long rows = rebuild.run();
        assertTrue(rows > 360, "rows " + rows);
        assertTrue(rebuild.getBackup().isDirectory(), "old database kept");
        assertFalse(new File(db.getParentFile(), db.getName() + "-rebuild").exists());

        try (Connection c = open(db)) {
            assertArrayEquals(counts, counts(c, tables));
            assertEquals(String.valueOf(Constants.DATABASE_VERSION), query(c, "SELECT value FROM globalsettings WHERE cname = 'yabs_dbversion'"));
            assertEquals("60.5", query(c, "SELECT CHAR(netvalue) FROM items WHERE cnumber = 'R60'"));
            assertEquals("2", query(c, "SELECT CHAR(reforderids) FROM items WHERE cnumber = 'G1'"));
            assertEquals("7", query(c, "SELECT CHAR(groupsids) FROM groups WHERE ids = 5"));
            assertEquals("2", query(c, "SELECT CHAR(ids) FROM productorders WHERE cname = 'B2'"));
            try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery("SELECT data FROM files")) {
                assertTrue(rs.next());
                assertArrayEquals(new byte[]{1, 2, 3}, rs.getBytes(1));
            }
            //new rows get new ids, the triggers work
            exec(c, "INSERT INTO items (cname, cnumber, dateadded, contactsids) VALUES ('Neu', 'R999', '2020-01-01', 1)",
                    "INSERT INTO productorders (cname, cnumber, dateadded, contactsids) VALUES ('B3', 'B3', '2020-01-01', 1)",
                    "ALTER TABLE items ADD COLUMN testcolumn SMALLINT DEFAULT 0");
            //after the copied ids (Derby may leave gaps)
            assertTrue(Long.parseLong(query(c, "SELECT CHAR(ids) FROM items WHERE cnumber = 'R999'")) > 121);
            assertTrue(Long.parseLong(query(c, "SELECT CHAR(ids) FROM productorders WHERE cname = 'B3'")) > 2);
            assertEquals(String.valueOf(counts[6] + 1), query(c, "SELECT CHAR(COUNT(*)) FROM searchindex"));
        }
    }

    private static long[] counts(Connection c, String[] tables) throws SQLException {
        long[] n = new long[tables.length];
        for (int i = 0; i < tables.length; i++) {
            n[i] = Long.parseLong(query(c, "SELECT CHAR(COUNT(*)) FROM " + tables[i]).trim());
        }
        return n;
    }
}
