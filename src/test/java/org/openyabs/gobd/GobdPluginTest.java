        assertEquals(GobdUtil.fmtExact(new BigDecimal("0.3")), GobdUtil.fmtExact(0.1d + 0.2d));
        assertEquals("a!%b!_c!!", GobdUtil.likeEscape("a%b_c!"));
        assertEquals("2026-11-18 10:00:05", GobdUtil.fmtTimestamp("2026-11-18 10:00:05.123"));
        assertEquals("2026-11-18 10:00:05", GobdUtil.fmtTimestamp(java.sql.Timestamp.valueOf("2026-11-18 10:00:05")));
        assertTrue(GobdUtil.inYear(java.sql.Date.valueOf("2026-03-01"), "2026"));
        assertEquals(2026, GobdUtil.yearOf(java.sql.Date.valueOf("2026-03-01")));
