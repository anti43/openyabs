    @Test
    public void theHashChainIsSha256OfFileAndPreviousHash() {
        byte[] file = "Rechnung".getBytes(StandardCharsets.UTF_8);
        assertEquals(64, GobdUtil.GENESIS_HASH.length());
        assertTrue(GobdUtil.GENESIS_HASH.matches("0{64}"));
        String first = GobdUtil.chained(file, GobdUtil.GENESIS_HASH);
        //SHA256(bytes || prev) is SHA256 of the concatenation
        byte[] both = ("Rechnung" + GobdUtil.GENESIS_HASH).getBytes(StandardCharsets.UTF_8);
        assertEquals(GobdUtil.sha256(both), first);
        assertNotEquals(first, GobdUtil.chained(file, first));
        //known value
        assertEquals("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", GobdUtil.sha256("abc".getBytes(StandardCharsets.UTF_8)));
    }

    @Test
    public void recordsAreCanonicalAndHashed() {
        String r = GobdUtil.record("a", 1, "b", "x\ny\\z", "c", null);
        assertEquals("a=1\nb=x\\ny\\\\z\nc=", r);
        assertEquals("x\\ny\\\\z", GobdUtil.recordField(r, "b"));
        assertEquals(GobdUtil.recordValue("x\ny\\z"), GobdUtil.recordField(r, "b"));
        assertNull(GobdUtil.recordField(r, "d"));
        assertEquals(GobdUtil.sha256((r + "\n" + GobdUtil.GENESIS_HASH).getBytes(StandardCharsets.UTF_8)), GobdUtil.recordHash(r, GobdUtil.GENESIS_HASH));
        //the same values give the same record, whether long or int, Timestamp or text
        String a = Gobd.documentRecord(3L, 7L, "RE-1", java.sql.Timestamp.valueOf("2026-01-02 03:04:05"), "u", "XML", "f", null, "core", "pos");
        String b = Gobd.documentRecord(3, 7, "RE-1", "2026-01-02 03:04:05.0", "u", "XML", "f", null, "core", "pos");
        assertEquals(a, b);
        assertEquals("-", Audit.diff(a, b));
        String c = Gobd.documentRecord(3, 7, "RE-1", "2026-01-02 03:04:05", "u", "XML", "f", null, "core2", "pos");
        assertEquals("core", Audit.diff(a, c));
        assertNotEquals(GobdUtil.recordHash(a, GobdUtil.GENESIS_HASH), GobdUtil.recordHash(c, GobdUtil.GENESIS_HASH));
        //receipts of expenses and income: the same record, with their own owner key
        String exp = Gobd.receiptRecord(1, "5", 9, "a.pdf", 10, "f", "2026-01-02 03:04:05", "u", "core");
        assertEquals(exp, Gobd.receiptRecord(Gobd.Receipts.EXPENSE, 1, "5", 9, "a.pdf", 10, "f", "2026-01-02 03:04:05", "u", "core"));
        String rev = Gobd.receiptRecord(Gobd.Receipts.REVENUE, 1, "5", 9, "a.pdf", 10, "f", "2026-01-02 03:04:05", "u", "core");
        assertEquals("9", GobdUtil.recordField(rev, "revenue_id"));
        assertNull(GobdUtil.recordField(rev, "expense_id"));
        assertEquals("revenue_receipts", Gobd.Receipts.REVENUE.table);
        assertEquals("gobd_revenue_receipt", Gobd.Receipts.REVENUE.chainTable);
    }

    @Test
    public void theAuditLogIsAHashChain() throws Exception {
        try (java.sql.Connection c = java.sql.DriverManager.getConnection("jdbc:h2:mem:gobdaudit")) {
            Db.update(c, "CREATE TABLE gobd_audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, user_id VARCHAR(100) NOT NULL, entity_type VARCHAR(50) NOT NULL,"
                    + " entity_id BIGINT NOT NULL, action VARCHAR(50) NOT NULL, old_value VARCHAR(2000) NULL, new_value VARCHAR(2000) NULL,"
                    + " file_hash CHAR(64) NULL, details VARCHAR(1000) NULL, prev_hash CHAR(64) NULL, row_hash CHAR(64) NULL)");
            Db.update(c, "CREATE UNIQUE INDEX gobd_audit_log_prev ON gobd_audit_log (prev_hash)");
            Gobd.logAudit(c, "INVOICE", 1, "FINALIZED", null, "new\nline", GobdUtil.GENESIS_HASH, "d");
            Gobd.logAudit(c, "INVOICE", 1, "PAYMENT", "a", "b", "", "d2");
            Gobd.logAudit(c, "PLUGIN", 0, "X", null, null, null, null);
            Object[][] rows = Db.query(c, "SELECT id, created_at, user_id, entity_type, entity_id, action, old_value, new_value, file_hash, details,"
                    + " prev_hash, row_hash FROM gobd_audit_log ORDER BY id");
            assertEquals(3, rows.length);
            String prev = GobdUtil.GENESIS_HASH;
            for (Object[] a : rows) {
                assertEquals(prev, a[10]);
                String rec = Gobd.auditRecord(a[1], (String) a[2], (String) a[3], a[4], (String) a[5], (String) a[6], (String) a[7], (String) a[8], (String) a[9]);
                assertEquals(GobdUtil.recordHash(rec, prev), a[11]);
                //the line of the text export alone is enough to check the hash (outside YaBS)
                String line = Audit.auditLine(a);
                String[] cells = line.substring(line.indexOf(';') + 2, line.length() - 1).split("\";\"", -1);
                assertEquals(11, cells.length, line);
                String[] keys = {"created_at", "user", "entity_type", "entity_id", "action", "old", "new", "file_hash", "details"};
                StringBuilder rebuilt = new StringBuilder();
                for (int i = 0; i < keys.length; i++) {
                    rebuilt.append(i == 0 ? "" : "\n").append(keys[i]).append('=').append(cells[i].replace("\"\"", "\""));
                }
                assertEquals(rec, rebuilt.toString());
                assertEquals(a[11], GobdUtil.recordHash(rebuilt.toString(), cells[9]));
                prev = (String) a[11];
            }
            //the check finds a changed entry
            java.util.List<String> errors = new java.util.ArrayList<String>();
            Audit.AuditChain chain = new Audit.AuditChain(errors);
            rows[1][7] = "changed";
            for (Object[] a : rows) {
                chain.accept(a);
            }
            assertEquals(3, chain.chained);
            assertEquals(1, errors.size(), String.valueOf(errors));
            assertTrue(Audit.auditLine(rows[0]).contains("new\\nline"), Audit.auditLine(rows[0]));
            //a second successor of the same link is refused (no fork)
            java.sql.SQLException e = org.junit.jupiter.api.Assertions.assertThrows(java.sql.SQLException.class, () -> Db.update(c,
                    "INSERT INTO gobd_audit_log (user_id, entity_type, entity_id, action, prev_hash, row_hash) VALUES ('u', 't', 1, 'a', ?, ?)",
                    GobdUtil.GENESIS_HASH, GobdUtil.GENESIS_HASH));
            assertTrue(Db.isUniqueViolation(e));
        }
    }

    @Test
    public void formatsAndEscaping() {
        assertEquals("0.00", GobdUtil.fmtDec(null));
        assertEquals("0.00", GobdUtil.fmtDec("x"));
        assertEquals("12.35", GobdUtil.fmtDec(new BigDecimal("12.345")));
        //BigDecimal, not double: 2.675 is 2.67499... as a double
        assertEquals("2.68", GobdUtil.fmtDec("2.675"));
        assertEquals("2.68", GobdUtil.fmtDec(2.675d));
        assertEquals("100.000001", GobdUtil.fmtExact(new BigDecimal("100.000001")));
        assertNotEquals(GobdUtil.fmtExact(100.0d), GobdUtil.fmtExact(100.004d));
        assertEquals(GobdUtil.fmtExact(new BigDecimal("0.3")), GobdUtil.fmtExact(0.1d + 0.2d));
        assertEquals("a!%b!_c!!", GobdUtil.likeEscape("a%b_c!"));
        assertEquals("2026-11-18 10:00:05", GobdUtil.fmtTimestamp("2026-11-18 10:00:05.123"));
        assertEquals("2026-11-18 10:00:05", GobdUtil.fmtTimestamp(java.sql.Timestamp.valueOf("2026-11-18 10:00:05")));
        assertTrue(GobdUtil.inYear(java.sql.Date.valueOf("2026-03-01"), "2026"));
        assertEquals(2026, GobdUtil.yearOf(java.sql.Date.valueOf("2026-03-01")));
        assertEquals("2026-11-18", GobdUtil.fmtDate("2026-11-18 10:00:00.0"));
        assertEquals("", GobdUtil.fmtDate(null));
        assertEquals("O''Reilly", GobdUtil.esc("O'Reilly"));
        assertEquals("a b \"\"c\"\"", GobdUtil.csvCell("a\r\nb \"c\""));
        assertEquals("&lt;a&gt; &amp; &quot;b&quot; &apos;c&apos;", GobdUtil.escapeXml("<a> & \"b\" 'c'"));
        assertEquals("abcd...", GobdUtil.trunc("abcdefghij", 7));
        assertTrue(GobdUtil.isDraftNumber(""));
        assertTrue(GobdUtil.isDraftNumber("Entwurf 3"));
        assertTrue(GobdUtil.isDraftNumber("draft"));
        assertFalse(GobdUtil.isDraftNumber("RE-2026-00001"));
        assertEquals("RE_2026_1.x", GobdUtil.safeFileName("RE/2026 1.x"));
        assertTrue(GobdUtil.isTrue("1"));
        assertTrue(GobdUtil.isTrue("TRUE"));
        assertFalse(GobdUtil.isTrue(null));
    }

    @Test
    public void readsACiiInvoice() throws Exception {
        String cii = "<rsm:CrossIndustryInvoice xmlns:rsm='urn:un:unece:uncefact:data:standard:CrossIndustryInvoice:100'"
                + " xmlns:ram='urn:un:unece:uncefact:data:standard:ReusableAggregateBusinessInformationEntity:100'"
                + " xmlns:udt='urn:un:unece:uncefact:data:standard:UnqualifiedDataType:100'>"
                + "<rsm:ExchangedDocument><ram:ID>RE-4711</ram:ID><ram:IssueDateTime><udt:DateTimeString format='102'>20261103</udt:DateTimeString></ram:IssueDateTime></rsm:ExchangedDocument>"
                + "<rsm:SupplyChainTradeTransaction><ram:ApplicableHeaderTradeAgreement><ram:SellerTradeParty><ram:Name>Muster GmbH</ram:Name></ram:SellerTradeParty></ram:ApplicableHeaderTradeAgreement>"
                + "<ram:ApplicableHeaderTradeSettlement><ram:ApplicableTradeTax><ram:RateApplicablePercent>19</ram:RateApplicablePercent></ram:ApplicableTradeTax>"
                + "<ram:SpecifiedTradePaymentTerms><ram:DueDateDateTime><udt:DateTimeString format='102'>20261203</udt:DateTimeString></ram:DueDateDateTime></ram:SpecifiedTradePaymentTerms>"
                + "<ram:SpecifiedTradeSettlementHeaderMonetarySummation><ram:TaxBasisTotalAmount>100.00</ram:TaxBasisTotalAmount>"
                + "<ram:GrandTotalAmount>119.00</ram:GrandTotalAmount></ram:SpecifiedTradeSettlementHeaderMonetarySummation>"
                + "</ram:ApplicableHeaderTradeSettlement></rsm:SupplyChainTradeTransaction></rsm:CrossIndustryInvoice>";
        EInvoice.Parsed p = EInvoice.parse(cii.getBytes(StandardCharsets.UTF_8));
        assertTrue(p.valid(), String.valueOf(p.errors));
        assertEquals("RE-4711", p.documentNumber);
        assertEquals("Muster GmbH", p.partnerName);
        assertEquals(new BigDecimal("100.00"), p.netAmount);
        assertEquals(new BigDecimal("119.00"), p.grossAmount);
        assertEquals(new BigDecimal("19.00"), p.taxPercent);
        SimpleDateFormat f = new SimpleDateFormat("yyyy-MM-dd");
        assertEquals("2026-11-03", f.format(p.issueDate));
        assertEquals("2026-12-03", f.format(p.dueDate));
    }

