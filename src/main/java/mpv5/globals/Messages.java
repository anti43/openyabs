    /**
     * @return the missing
     */
    public static List<String> getMissing() {
        return Collections.unmodifiableList(missing);
    }

    private Messages(String message) {
      this.message = message;
    }
    private String message;
    private static List<String> missing = new ArrayList<String>();

    public void addMessage(String message) {
        missing.add(message);
    }

    @Override
    public String toString() {

        if(missing.contains(name())) {
            String de = LanguageManager.fallback(name());
            return de != null ? de : message;
        }
        try {
            return LanguageManager.localize(name(), LanguageManager.getBundle().getString(name()));
        } catch (Exception e) {
            Log.Debug(this, e.getMessage());
            addMessage(name());
            //a new text, not yet in the language of the database
            String de = LanguageManager.fallback(name());
            if (de != null) {
                return de;
            }
        }

        if (message == null) {
            return super.toString();
        } else {
            return message;
        }
    }

    /**
     * Refers to toString()
     *
     * @return The value for this enum
     */
    public String getValue() {
        return toString();
    }
    
    public String rawMessage() {
        return this.message;
    } 
