    /**
     * The triggers of the search index and the trash bin for MySQL (from
     * {@link Schema}), then the search index and the trash bin filled from
     * the existing data. Optional: without the TRIGGER privilege (or with
     * binary logging and log_bin_trust_function_creators=0) the update goes
     * on, see {@link SchemaUpdate#getWarnings()}.
     *
     * @return the statements
     */
    static String[] mysqlTriggers() {
        java.util.List<String> l = new java.util.ArrayList<String>();
        java.util.List<String> fill = new java.util.ArrayList<String>();
        for (String t : Schema.get().getTriggers()) {
            SqlDialect.Trigger tr = SqlDialect.Trigger.parse(t);
            l.add(SchemaUpdate.OPTIONAL + "DROP TRIGGER IF EXISTS " + tr.name);
            for (String q : SqlDialect.MYSQL.trigger(t)) {
                l.add(SchemaUpdate.OPTIONAL + q);
            }
            //the rows the insert/update triggers would have written for the existing data
            String fromRows = SqlDialect.copyRows(tr);
            if (fromRows != null) {
                fill.add(fromRows);
            }
        }
        l.add("DELETE FROM searchindex");
        l.add("DELETE FROM trashbin");
        l.addAll(fill);
        return l.toArray(new String[0]);
    }

    /**
     * Update the database from the specified to the max
     * available version
     *
     * @param version
     * @throws java.lang.Exception
     */
    /**
     * Tables a database at the current version must have: version -> table.
     * A database whose version was raised without them (an interrupted or
     * failed update of an older YaBS) gets them on the next start.
     */
    private static final Map<Double, String> REQUIRED_TABLES = new TreeMap<Double, String>(Map.of(1.1987, "payments"));

    /**
     * Creates missing tables of {@link #REQUIRED_TABLES} with the statements of
     * their update
     *
     * @param c the connection
     */
    public static void ensureTables(Connection c) {
        boolean derby = ConnectionTypeHandler.isDerbyLike();
        boolean h2 = ConnectionTypeHandler.getDriverType() == ConnectionTypeHandler.H2;
        boolean postgres = ConnectionTypeHandler.getDriverType() == ConnectionTypeHandler.POSTGRES;
        DatabaseUpdater u = new DatabaseUpdater();
        ensureTables(c, postgres ? u.UPDATES_POSTGRES : h2 ? H2Dialect.convert(u.UPDATES_DERBY) : derby ? u.UPDATES_DERBY : u.UPDATES_MYSQL,
                ConnectionTypeHandler.getDriverType() == ConnectionTypeHandler.MYSQL);
    }

    /**
     * @param c
     * @param updates the updates of the database type
     * @param mysql
     */
    static void ensureTables(Connection c, Map<Double, String[]> updates, boolean mysql) {
        MISSING_TABLES.clear();
        for (Map.Entry<Double, String> e : REQUIRED_TABLES.entrySet()) {
            try {
                if (tableExists(c, e.getValue(), mysql)) {
                    continue;
                }
                Log.Print("DatabaseUpdater: table " + e.getValue() + " is missing, creating it");
                for (String sql : updates.get(e.getKey())) {
                    try (Statement s = c.createStatement()) {
                        s.execute(DatabaseConnection.withPrefix(sql));
                    } catch (SQLException ex) {
                        Log.Debug(DatabaseUpdater.class, ex.getMessage());
                        String plain = sql.replaceAll(" REFERENCES \\w+\\(\\w+\\)( ON DELETE CASCADE)?", "");
                        if (!plain.equals(sql)) {
                            //an old table without primary key can not be referenced: without the reference
                            try (Statement s = c.createStatement()) {
                                s.execute(DatabaseConnection.withPrefix(plain));
                            } catch (SQLException ex2) {
                                Log.Debug(DatabaseUpdater.class, ex2.getMessage());
                            }
                        }
                    }
                }
                if (!tableExists(c, e.getValue(), mysql)) {
                    MISSING_TABLES.add(e.getValue());
                    Log.Print("DatabaseUpdater: table " + e.getValue() + " could not be created, its function is off");
                } else {
                    Log.Print("DatabaseUpdater: table " + e.getValue() + " created");
                }
            } catch (Exception ex) {
                Log.Debug(DatabaseUpdater.class, ex);
            }
        }
    }

    private static final java.util.Set<String> MISSING_TABLES = java.util.concurrent.ConcurrentHashMap.newKeySet();

    /**
     * @param table
     * @return false if the table is missing and could not be created: the
     * function using it is off
     */
    public static boolean hasTable(String table) {
        return !MISSING_TABLES.contains(table);
    }

    /**
     * @param c
     * @param table
     * @param mysql not used any more (kept for the callers)
     * @return true if the table can be queried with the connection, exactly
     * as the application queries it (schema, letter case)
     */
    static boolean tableExists(Connection c, String table, boolean mysql) throws SQLException {
        boolean auto = c.getAutoCommit();
        try (Statement s = c.createStatement()) {
            s.executeQuery("SELECT COUNT(*) FROM " + table + " WHERE 1 = 0").close();
            return true;
        } catch (SQLException e) {
            Log.Debug(DatabaseUpdater.class, "Table " + table + " can not be queried: " + e.getMessage());
            if (!auto) {
                //PostgreSQL: a failed statement aborts the transaction
                c.rollback();
            }
            return false;
        }
    }

    public void updateFrom(double version) throws Exception {
        Log.Debug(DatabaseUpdater.class, "Updating database from " + version);
        boolean derby = ConnectionTypeHandler.isDerbyLike();
        boolean h2 = ConnectionTypeHandler.getDriverType() == ConnectionTypeHandler.H2;
        boolean postgres = ConnectionTypeHandler.getDriverType() == ConnectionTypeHandler.POSTGRES;
        SchemaUpdate update = new SchemaUpdate(reconnect -> {
            try {
                DatabaseConnection dc = DatabaseConnection.instanceOf();
                if (reconnect || dc.getConnection() == null || dc.getConnection().isClosed()) {
                    dc.reconnect(false);
                }
                return dc.getConnection();
            } catch (SQLException e) {
                throw e;
            } catch (Exception e) {
                throw new SQLException(e);
            }
        }, derby, DatabaseConnection::withPrefix);
        try {
            double newVersion = update.run(version, postgres ? UPDATES_POSTGRES : h2 ? H2Dialect.convert(UPDATES_DERBY) : derby ? UPDATES_DERBY : UPDATES_MYSQL);
            if (!SchemaUpdate.getWarnings().isEmpty()) {
                mpv5.ui.dialogs.Popup.notice(mpv5.globals.Messages.DB_UPDATE_WARNINGS + "\n\n" + String.join("\n", SchemaUpdate.getWarnings()));
            }
            Log.Debug(DatabaseUpdater.class, "Database updated to " + newVersion);
        } catch (SchemaUpdate.DamagedDatabaseException e) {
            Log.Debug(e);
            if (!derby || h2) {
                throw e;
            }
            rebuild(e);
        }
    }

    /**
     * The Derby catalog is damaged: offer to copy all data into a new database
     */
    private void rebuild(SchemaUpdate.DamagedDatabaseException cause) throws Exception {
        File db = new File(DatabaseConnection.instanceOf().getCtype().getURL(), ConnectionTypeHandler.getDBNAME());
        if (!db.isDirectory()) {
            //network server (//host:port/...) or unknown location: can only be repaired on the server
            throw cause;
        }
        boolean de = Locale.getDefault().getLanguage().equals("de");
        String question = de
                ? "Die Datenbank kann nicht aktualisiert werden, ihre interne Struktur (Trigger) ist beschädigt:\n"
                + cause.getCause().getMessage() + "\n\n"
                + "YaBS kann alle Daten in eine neu angelegte Datenbank kopieren. Die alte Datenbank bleibt "
                + "unverändert als Sicherung erhalten (" + db.getName() + "-backup-<Datum>).\n"
                + "Bei großen Datenbanken kann das einige Minuten dauern.\n\nJetzt neu aufbauen?"
                : "The database can not be updated, its internal structure (triggers) is damaged:\n"
                + cause.getCause().getMessage() + "\n\n"
                + "YaBS can copy all data into a newly created database. The old database is kept unchanged "
                + "as backup (" + db.getName() + "-backup-<date>).\n"
                + "This can take some minutes for large databases.\n\nRebuild now?";
        if (!Popup.Y_N_dialog(question, de ? "Datenbank neu aufbauen" : "Rebuild database")) {
            throw cause;
        }
        DatabaseConnection.shutdown();
        DerbyRebuild rebuild = new DerbyRebuild(db, DatabaseConnection.getUser(), DatabaseConnection.getPassword(),
                DatabaseInstallation.DERBY_STRUCTURE, DatabaseInstallation.INITIAL_DATA, UPDATES_DERBY,
                DatabaseConnection::withPrefix);
        long rows = rebuild.run();
        DatabaseConnection.instanceOf().reconnect(false);
        Popup.OK_dialog(de
                ? "Die Datenbank wurde neu aufgebaut (" + rows + " Datensätze kopiert).\nDie alte Datenbank liegt in " + rebuild.getBackup()
                : "The database was rebuilt (" + rows + " rows copied).\nThe old database is in " + rebuild.getBackup(),
                de ? "Datenbank neu aufgebaut" : "Database rebuilt");
    }

    public Map<Double, String[]> getStructureForMigration(int conType) {
        switch (conType) {
            case ConnectionTypeHandler.DERBY:
                return UPDATES_DERBY;
            case ConnectionTypeHandler.H2:
                return H2Dialect.convert(UPDATES_DERBY);
            case ConnectionTypeHandler.MYSQL:
                return UPDATES_MYSQL;
            case ConnectionTypeHandler.POSTGRES:
                return UPDATES_POSTGRES;
            default:
                return null;
        }
    }
