package mpv5.db.common;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Converts the neutral SQL of {@link Schema} (and of future updates) for one
 * database. The tables are nearly portable; what differs: identity columns
 * (MySQL AUTO_INCREMENT), large objects (PostgreSQL BYTEA/TEXT, MySQL
 * LONGBLOB/LONGTEXT), TIMESTAMP (MySQL DATETIME), long VARCHARs (MySQL row
 * size: TEXT) and above all the triggers of the search index and the trash
 * bin:
 * <ul>
 * <li>H2: the Java trigger {@link H2Trigger} runs the stored statement</li>
 * <li>PostgreSQL: one PL/pgSQL function per trigger</li>
 * <li>MySQL/MariaDB: row triggers; the statement triggers on the trash bin
 * (MySQL can not change the table of the trigger) are folded into the trash
 * triggers of each table</li>
 * </ul>
 */
public enum SqlDialect {

    H2 {
        @Override
        List<String> convert(String sql) {
            return List.of(sql);
        }

        @Override
        List<String> trigger(String derby) {
            return List.of(H2Dialect.convert(derby));
        }
    },
    POSTGRES {
        @Override
        List<String> convert(String sql) {
            String r = BLOB.matcher(sql).replaceAll("BYTEA");
            r = CLOB.matcher(r).replaceAll("TEXT");
            return List.of(r);
        }

        @Override
        List<String> trigger(String derby) {
            Trigger t = Trigger.parse(derby);
            if (TRASH_DEDUPE.matcher(t.statement).find()) {
                //HAVING without GROUP BY is Derby/H2 only: the older rows of an object go
                t.statement = "DELETE FROM trashbin WHERE EXISTS (SELECT 1 FROM trashbin newer WHERE newer.cname = trashbin.cname"
                        + " AND newer.rowid = trashbin.rowid AND newer.ids > trashbin.ids)";
            }
            String body = t.alias == null ? t.statement
                    : aliasPattern(t.alias).matcher(t.statement).replaceAll(t.old ? "OLD." : "NEW.");
            String fn = t.name + "_fn";
            return List.of(
                    "CREATE OR REPLACE FUNCTION " + fn + "() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN " + body
                    + "; RETURN NULL; END $$",
                    "CREATE TRIGGER " + t.name + " " + t.timing + " " + t.event + " ON " + t.table
                    + (t.row ? " FOR EACH ROW" : " FOR EACH STATEMENT") + " EXECUTE FUNCTION " + fn + "()");
        }
    },
    MYSQL {
        @Override
        List<String> convert(String sql) {
            if (!sql.regionMatches(true, 0, "CREATE TABLE", 0, 12)) {
                return List.of(sql);
            }
            String r = sql.replace("GENERATED BY DEFAULT AS IDENTITY", "AUTO_INCREMENT");
            //an AUTO_INCREMENT column must be a key
            Matcher auto = Pattern.compile("(?m)^\\s*(\\w+) \\w+ AUTO_INCREMENT").matcher(r);
            if (auto.find() && !r.contains("PRIMARY KEY") && !r.matches("(?s).*UNIQUE \\(" + auto.group(1) + "\\).*")) {
                r = r.substring(0, r.lastIndexOf(')')).replaceAll("\\s+$", "") + ",\n  UNIQUE (" + auto.group(1) + ")\n)";
            }
            r = TIMESTAMP.matcher(r).replaceAll("DATETIME");
            r = BLOB.matcher(r).replaceAll("LONGBLOB");
            r = CLOB.matcher(r).replaceAll("LONGTEXT");
            //rows are limited to 65535 bytes (utf8mb4: 4 per character): long texts are TEXT
            Matcher m = VARCHAR.matcher(r);
            StringBuilder b = new StringBuilder();
            while (m.find()) {
                int n = Integer.parseInt(m.group(1));
                m.appendReplacement(b, n > 2000 ? (n > 16000 ? "MEDIUMTEXT" : "TEXT") : m.group());
            }
            m.appendTail(b);
            return List.of(b + " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
        }

        @Override
        List<String> trigger(String derby) {
            Trigger t = Trigger.parse(derby);
            if (!t.row) {
                //the clean-up of the trash bin is part of the trash triggers below
                return List.of();
            }
            String prefix = t.old ? "OLD." : "NEW.";
            String body = concat(aliasPattern(t.alias).matcher(t.statement).replaceAll(prefix));
            Matcher trash = TRASH_INSERT.matcher(body);
            if (trash.matches()) {
                //the trash bin keeps one row per object, only while it is invisible
                Map<String, String> v = columnValues(trash.group(1), trash.group(2));
                body = "BEGIN DELETE FROM trashbin WHERE cname = " + v.get("cname") + " AND rowid = " + v.get("rowid") + "; "
                        + "IF " + v.get("deleteme") + " <> 0 THEN " + body + "; END IF; END";
            }
            return List.of("CREATE TRIGGER " + t.name + " " + t.timing + " " + t.event + " ON " + t.table + " FOR EACH ROW " + body);
        }
    };

    private static final Pattern BLOB = Pattern.compile("\\bBLOB\\b");
    private static final Pattern CLOB = Pattern.compile("\\bCLOB\\b");
    private static final Pattern TIMESTAMP = Pattern.compile("\\bTIMESTAMP\\b");
    private static final Pattern VARCHAR = Pattern.compile("\\bVARCHAR\\((\\d+)\\)");
    private static final Pattern TRASH_DEDUPE = Pattern.compile("(?i)HAVING\\s+trashbin\\.ids\\s*<\\s*MAX\\(tmptable\\.ids\\)");
    private static final Pattern TRASH_INSERT = Pattern.compile("(?is)^INSERT INTO trashbin\\s*\\(([^)]*)\\)\\s*VALUES\\s*\\((.*)\\)\\s*$");

    /**
     * @param sql a neutral statement (table, index, key, data)
     * @return the statements for this database
     */
    abstract List<String> convert(String sql);

    /**
     * @param derby a trigger in Derby syntax
     * @return the statements for this database (none if not possible)
     */
    abstract List<String> trigger(String derby);

    /**
     * @param driverType {@link ConnectionTypeHandler#getDriverType()}
     * @return the dialect, null for Derby (old structure and updates) and
     * unknown drivers
     */
    public static SqlDialect of(Integer driverType) {
        if (driverType == null) {
            return null;
        }
        switch (driverType) {
            case ConnectionTypeHandler.H2:
                return H2;
            case ConnectionTypeHandler.POSTGRES:
                return POSTGRES;
            case ConnectionTypeHandler.MYSQL:
                return MYSQL;
            default:
                return null;
        }
    }

    private static Pattern aliasPattern(String alias) {
        return Pattern.compile("(?i)\\b" + Pattern.quote(alias) + "\\.");
    }

    /**
     * A trigger in Derby syntax
     */
    static final class Trigger {

        private static final Pattern P = Pattern.compile(
                "(?is)^\\s*CREATE\\s+TRIGGER\\s+(\\w+)\\s+(AFTER|BEFORE|NO\\s+CASCADE\\s+BEFORE)\\s+(INSERT|UPDATE|DELETE)\\s+ON\\s+(\\w+)\\s+(.*)$");
        private static final Pattern ROW = Pattern.compile("(?is)^REFERENCING\\s+(NEW|OLD)(?:\\s+ROW)?\\s+AS\\s+(\\w+)\\s+FOR\\s+EACH\\s+ROW\\s+(.*)$");
        private static final Pattern STATEMENT = Pattern.compile("(?is)^FOR\\s+EACH\\s+(ROW|STATEMENT)\\s+(.*)$");
        String name, timing, event, table, alias, statement;
        boolean row, old;

        static Trigger parse(String sql) {
            Matcher m = P.matcher(sql.trim());
            if (!m.matches()) {
                throw new IllegalArgumentException("No trigger: " + sql);
            }
            Trigger t = new Trigger();
            t.name = m.group(1);
            t.timing = m.group(2).toUpperCase().endsWith("BEFORE") ? "BEFORE" : "AFTER";
            t.event = m.group(3).toUpperCase();
            t.table = m.group(4);
            String rest = m.group(5).trim();
            Matcher r = ROW.matcher(rest);
            if (r.matches()) {
                t.row = true;
                t.old = r.group(1).equalsIgnoreCase("OLD");
                t.alias = r.group(2);
                t.statement = r.group(3).trim();
            } else {
                Matcher s = STATEMENT.matcher(rest);
                if (!s.matches()) {
                    throw new IllegalArgumentException("Unknown trigger: " + sql);
                }
                t.row = s.group(1).equalsIgnoreCase("ROW");
                t.statement = s.group(2).trim();
            }
            return t;
        }
    }

    /**
     * Splits at top-level commas (not in quotes or parentheses)
     */
    static List<String> splitTop(String s, String sep) {
        List<String> l = new ArrayList<String>();
        int depth = 0;
        boolean quote = false;
        int start = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\'') {
                quote = !quote;
            } else if (!quote && c == '(') {
                depth++;
            } else if (!quote && c == ')') {
                depth--;
            } else if (!quote && depth == 0 && s.startsWith(sep, i)) {
                l.add(s.substring(start, i).trim());
                start = i + sep.length();
                i += sep.length() - 1;
            }
        }
        l.add(s.substring(start).trim());
        return l;
    }

    private static Map<String, String> columnValues(String columns, String values) {
        Map<String, String> m = new LinkedHashMap<String, String>();
        List<String> c = splitTop(columns, ",");
        List<String> v = splitTop(values, ",");
        for (int i = 0; i < c.size() && i < v.size(); i++) {
            m.put(c.get(i).toLowerCase(), v.get(i));
        }
        return m;
    }

    private static final Pattern INSERT_VALUES = Pattern.compile("(?is)^INSERT INTO (searchindex|trashbin)\\s*\\(([^)]*)\\)\\s*VALUES\\s*\\((.*)\\)\\s*$");

    /**
     * MySQL: the rows a trigger would have written for the existing data -
     * the search index (insert triggers) and the trash bin (update triggers,
     * invisible rows)
     *
     * @param t a trigger
     * @return INSERT ... SELECT, null if the trigger writes no such rows
     */
    static String copyRows(Trigger t) {
        if (!t.row) {
            return null;
        }
        Matcher m = INSERT_VALUES.matcher(t.statement);
        if (!m.matches()) {
            return null;
        }
        boolean index = m.group(1).equalsIgnoreCase("searchindex");
        if (index != t.event.equals("INSERT")) {
            return null;
        }
        String values = aliasPattern(t.alias).matcher(m.group(3)).replaceAll("");
        String select = concat("INSERT INTO x () VALUES (" + values + ")");
        select = select.substring(select.indexOf("VALUES (") + 8, select.length() - 1);
        return "INSERT INTO " + m.group(1) + " (" + m.group(2) + ") SELECT " + select + " FROM " + t.table
                + (index ? "" : " WHERE invisible <> 0");
    }

    /**
     * MySQL: a || b becomes CONCAT(a, b) (|| is OR there)
     */
    static String concat(String sql) {
        if (!sql.contains("||")) {
            return sql;
        }
        Matcher m = Pattern.compile("(?is)^(.*?\\bVALUES\\s*\\()(.*)(\\)\\s*)$").matcher(sql);
        if (!m.matches()) {
            return sql;
        }
        List<String> out = new ArrayList<String>();
        for (String v : splitTop(m.group(2), ",")) {
            List<String> parts = splitTop(v, "||");
            out.add(parts.size() > 1 ? "CONCAT(" + String.join(", ", parts) + ")" : v);
        }
        return m.group(1) + String.join(", ", out) + m.group(3);
    }
}
