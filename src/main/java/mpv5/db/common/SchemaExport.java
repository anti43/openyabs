package mpv5.db.common;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import mpv5.globals.Constants;

/**
 * Writes the database structure of the current version as one neutral SQL
 * file ({@link Schema#RESOURCE}): the Derby structure and all updates are run
 * on an in-memory H2 database, then tables, keys, indexes, triggers and the
 * rows added by updates are read back. New databases (H2, MySQL/MariaDB,
 * PostgreSQL) are created from this file, converted by {@link SqlDialect};
 * the updates only run for existing databases.
 * <p>
 * Run after adding an update: {@code ./gradlew generateSchema} (the test
 * SchemaFileTest fails while the file is out of date).
 */
public final class SchemaExport {

    private SchemaExport() {
    }

    /**
     * Seed rows the updates need (group, user, version) - not part of the
     * file, the initial data of the installation provides them
     */
    private static final String[] SEED = {
        "INSERT INTO groups (cname, description, dateadded) VALUES ('seed', '', '2009-04-03')",
        "INSERT INTO users (fullname, password, cname, laf, locale, mail, language, inthighestright, datelastlog, isenabled, dateadded)"
        + " VALUES ('seed', 'x', 'seed', '', 'de_DE', '', 'buildin_en', 0, '2009-04-03', 1, '2009-04-03')",
        "INSERT INTO globalsettings (cname, groupsids, value) VALUES ('yabs_dbversion', 1, '1.0')"
    };

    /**
     * Tables whose rows are not exported (seed rows, trigger output, H2
     * internals)
     */
    private static final List<String> NO_DATA = List.of("groups", "users", "globalsettings", "searchindex", "trashbin",
            "yabstriggers", "history");

    /**
     * @return the neutral schema of the current version
     * @throws SQLException
     */
    public static String generate() throws SQLException {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:schemaexport" + System.nanoTime()
                + ";MODE=Derby;DEFAULT_NULL_ORDERING=HIGH;NON_KEYWORDS=" + H2Dialect.NON_KEYWORDS, "sa", "")) {
            new SchemaUpdate(r -> c, true, null).runAll(H2Dialect.convert(DatabaseInstallation.DERBY_STRUCTURE));
            try (Statement s = c.createStatement()) {
                for (String q : SEED) {
                    s.execute(q);
                }
            }
            double v = new SchemaUpdate(r -> c, true, null).run(1.0,
                    H2Dialect.convert(new DatabaseUpdater().getStructureForMigration(ConnectionTypeHandler.DERBY)));
            return write(c, v);
        }
    }

    private static List<String[]> rows(Connection c, String sql, String... args) throws SQLException {
        List<String[]> l = new ArrayList<String[]>();
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < args.length; i++) {
                ps.setString(i + 1, args[i]);
            }
            try (ResultSet rs = ps.executeQuery()) {
                int n = rs.getMetaData().getColumnCount();
                while (rs.next()) {
                    String[] r = new String[n];
                    for (int i = 0; i < n; i++) {
                        r[i] = rs.getString(i + 1);
                    }
                    l.add(r);
                }
            }
        }
        return l;
    }

    private static String lower(String s) {
        return s == null ? null : s.toLowerCase(Locale.ROOT);
    }

    private static String write(Connection c, double version) throws SQLException {
        StringBuilder b = new StringBuilder();
        b.append("-- YaBS database structure, version ").append(version).append('\n')
                .append("-- Generated by mpv5.db.common.SchemaExport from the Derby structure and all updates.\n")
                .append("-- Do not edit: after adding an update run ./gradlew generateSchema\n")
                .append("-- Neutral SQL, converted for H2, MySQL/MariaDB and PostgreSQL by mpv5.db.common.SqlDialect.\n\n");

        List<String> tables = new ArrayList<String>();
        for (String[] r : rows(c, "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'PUBLIC'"
                + " AND TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME <> 'YABSTRIGGERS' ORDER BY TABLE_NAME")) {
            tables.add(r[0]);
        }

        b.append("-- tables\n");
        for (String t : tables) {
            b.append("CREATE TABLE ").append(lower(t)).append(" (\n");
            List<String> parts = new ArrayList<String>();
            for (String[] col : rows(c, "SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_IDENTITY, COLUMN_DEFAULT, IS_NULLABLE"
                    + " FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION", t)) {
                StringBuilder p = new StringBuilder("  ").append(lower(col[0])).append(' ').append(type(col[1], col[2]));
                if ("YES".equals(col[3])) {
                    p.append(" GENERATED BY DEFAULT AS IDENTITY");
                } else if (col[4] != null) {
                    p.append(" DEFAULT ").append(col[4]);
                }
                if ("NO".equals(col[5])) {
                    p.append(" NOT NULL");
                }
                parts.add(p.toString());
            }
            for (String[] k : rows(c, "SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS"
                    + " WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? AND CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')"
                    + " ORDER BY CONSTRAINT_TYPE, CONSTRAINT_NAME", t)) {
                parts.add("  " + k[1] + " (" + columns(c, k[0]) + ")");
            }
            b.append(String.join(",\n", parts)).append("\n);\n\n");
        }

        b.append("-- indexes\n");
        for (String[] i : rows(c, "SELECT INDEX_NAME, TABLE_NAME, INDEX_TYPE_NAME FROM INFORMATION_SCHEMA.INDEXES"
                + " WHERE TABLE_SCHEMA = 'PUBLIC' AND IS_GENERATED = FALSE AND TABLE_NAME <> 'YABSTRIGGERS' ORDER BY TABLE_NAME, INDEX_NAME")) {
            StringBuilder cols = new StringBuilder();
            for (String[] ic : rows(c, "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.INDEX_COLUMNS WHERE TABLE_SCHEMA = 'PUBLIC'"
                    + " AND INDEX_NAME = ? ORDER BY ORDINAL_POSITION", i[0])) {
                cols.append(cols.length() == 0 ? "" : ", ").append(lower(ic[0]));
            }
            b.append("CREATE ").append("UNIQUE INDEX".equals(i[2]) ? "UNIQUE " : "").append("INDEX ").append(lower(i[0]))
                    .append(" ON ").append(lower(i[1])).append(" (").append(cols).append(");\n");
        }

        b.append("\n-- foreign keys\n");
        for (String[] f : rows(c, "SELECT tc.TABLE_NAME, rc.CONSTRAINT_NAME, rc.UNIQUE_CONSTRAINT_NAME, rc.DELETE_RULE"
                + " FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc"
                + " ON tc.CONSTRAINT_NAME = rc.CONSTRAINT_NAME AND tc.CONSTRAINT_SCHEMA = rc.CONSTRAINT_SCHEMA"
                + " WHERE rc.CONSTRAINT_SCHEMA = 'PUBLIC' ORDER BY tc.TABLE_NAME, rc.CONSTRAINT_NAME")) {
            String target = rows(c, "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = 'PUBLIC'"
                    + " AND CONSTRAINT_NAME = ?", f[2]).get(0)[0];
            String cols = columns(c, f[1]);
            b.append("ALTER TABLE ").append(lower(f[0])).append(" ADD CONSTRAINT fk_").append(lower(f[0])).append('_')
                    .append(cols.replace(", ", "_")).append(" FOREIGN KEY (").append(cols).append(") REFERENCES ")
                    .append(lower(target)).append(" (").append(columns(c, f[2])).append(')')
                    .append("CASCADE".equals(f[3]) ? " ON DELETE CASCADE" : "").append(";\n");
        }

        b.append("\n-- triggers (Derby syntax; H2: mpv5.db.common.H2Trigger, PostgreSQL: functions, MySQL: compound row triggers)\n");
        for (String[] tr : rows(c, "SELECT t.TRIGGER_NAME, t.ACTION_TIMING, t.EVENT_MANIPULATION, t.EVENT_OBJECT_TABLE, y.BODY"
                + " FROM INFORMATION_SCHEMA.TRIGGERS t JOIN YABSTRIGGERS y ON y.CNAME = t.TRIGGER_NAME"
                + " WHERE t.TRIGGER_SCHEMA = 'PUBLIC' ORDER BY t.EVENT_OBJECT_TABLE, t.TRIGGER_NAME")) {
            b.append("CREATE TRIGGER ").append(lower(tr[0])).append(' ').append(tr[1]).append(' ').append(tr[2])
                    .append(" ON ").append(lower(tr[3])).append(' ').append(tr[4].trim().replaceAll("\\s+", " ")).append(";\n");
        }

        b.append("\n-- rows added by updates (after the initial data)\n");
        for (String t : tables) {
            if (NO_DATA.contains(lower(t))) {
                continue;
            }
            try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery("SELECT * FROM " + t + " ORDER BY ids")) {
                ResultSetMetaData md = rs.getMetaData();
                while (rs.next()) {
                    List<String> names = new ArrayList<String>();
                    List<String> values = new ArrayList<String>();
                    for (int i = 1; i <= md.getColumnCount(); i++) {
                        Object o = rs.getObject(i);
                        if (o == null || "IDS".equalsIgnoreCase(md.getColumnName(i))) {
                            continue;
                        }
                        names.add(lower(md.getColumnName(i)));
                        values.add(o instanceof Number ? o.toString()
                                : o instanceof java.util.Date ? "'" + new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(o) + "'"
                                : "'" + String.valueOf(o).replace("'", "''") + "'");
                    }
                    b.append("INSERT INTO ").append(lower(t)).append(" (").append(String.join(", ", names)).append(") VALUES (")
                            .append(String.join(", ", values)).append(");\n");
                }
            }
        }
        return b.toString();
    }

    private static String columns(Connection c, String constraint) throws SQLException {
        List<String> l = new ArrayList<String>();
        for (String[] r : rows(c, "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE WHERE CONSTRAINT_SCHEMA = 'PUBLIC'"
                + " AND CONSTRAINT_NAME = ? ORDER BY ORDINAL_POSITION", constraint)) {
            l.add(lower(r[0]));
        }
        return String.join(", ", l);
    }

    /**
     * @return the neutral type: BIGINT, INTEGER, VARCHAR(n), DOUBLE PRECISION,
     * TIMESTAMP, BLOB, CLOB
     */
    private static String type(String h2, String length) {
        switch (h2) {
            case "CHARACTER VARYING":
                return "VARCHAR(" + length + ")";
            case "BINARY LARGE OBJECT":
                return "BLOB";
            case "CHARACTER LARGE OBJECT":
                return "CLOB";
            case "DATE":
                return "TIMESTAMP";
            default:
                return h2;
        }
    }

    /**
     * Writes the file: {@code SchemaExport <target file>}
     *
     * @param args the target, default src/main/resources/db/schema.sql
     * @throws Exception
     */
    public static void main(String[] args) throws Exception {
        File f = new File(args.length > 0 ? args[0] : "src/main/resources" + Schema.RESOURCE);
        f.getParentFile().mkdirs();
        Files.writeString(f.toPath(), generate(), StandardCharsets.UTF_8);
        System.out.println("Written: " + f + " (version " + Constants.DATABASE_VERSION + ")");
    }
}
