    /**
     * true while the invoices are created: a second click on "next" must not
     * create them again
     */
    private volatile boolean running;

    /**
     * Creates the invoices. Runs on the thread of the wizard ("next"), not on
     * the event dispatch thread: the panels and the database are used on the
     * EDT (short), creating and validating e-invoices runs here, so the window
     * stays responsive and the progress bar shows what is going on.
     */
    private void doit() throws NodataFoundException {
        if (running) {
            return;
        }
        //asked before anything is created: nothing is sent without confirmation
        final boolean send = email.isSelected() && confirmEmail();
        if (email.isSelected() && !send) {
            return;
        }
        final boolean createEInvoice = einvoice.isSelected();
        final javax.swing.JProgressBar bar = master.getProgressbar();
        final java.util.HashMap<String, Object> mails = new java.util.HashMap<String, Object>();
        final int total = data.size();
        //files written from now on (in the folders of the new invoices) are listed at the end;
        //a little earlier because of the time resolution of some file systems
        final long started = System.currentTimeMillis() - 2000;
        final List<Item> createdItems = new java.util.ArrayList<Item>();
        running = true;
        onEdt(() -> {
            setControlsEnabled(false);
            bar.setMinimum(0);
            bar.setMaximum(total);
            bar.setValue(0);
            bar.setStringPainted(true);
            setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            jTextArea2.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        });
        try {
            int index = 0;
            for (Map.Entry<Contact, List<Item>> entry : data.entrySet()) {
                final Contact key = entry.getKey();
                final List<Item> value = entry.getValue();
                final int number = ++index;
                progress(bar, number, total, key + ": " + mpv5.globals.Messages.ACTION_CREATING, false);
                final Item[] created = {null};
                onEdt(() -> created[0] = createInvoice(key, value, createEInvoice));
                if (created[0] == null) {
                    continue;
                }
                createdItems.add(created[0]);
                if (createEInvoice) {
                    //creating and checking takes a few seconds (the first check longer: the rules are loaded)
                    progress(bar, number, total, created[0].__getCnumber() + ": " + mpv5.globals.Messages.MASSEXPORT_EINVOICE_CHECKING, true);
                    final List<String> lines = mpv5.utils.export.EInvoiceFiles.write(created[0], key,
                            mpv5.db.objects.User.getSaveDir(created[0]));
                    onEdt(() -> {
                        for (String line : lines) {
                            jTextArea2.append("   " + line + "\n");
                        }
                    });
                }
                if (send) {
                    mails.put(created[0].__getCnumber(), created[0]);
                }
                final int done = number;
                onEdt(() -> {
                    mpv5.ui.modern.Edt.setIndeterminate(bar, false);
                    bar.setValue(done);
                });
            }
        } finally {
            running = false;
            onEdt(() -> {
                mpv5.ui.modern.Edt.setIndeterminate(bar, false);
                bar.setString(mpv5.globals.Messages.DONE.toString());
                setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
                jTextArea2.setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
                if (!mails.isEmpty()) {
                    //the serial mail of the overview: e-invoice per contact setting,
                    //incomplete e-invoices are not sent, log and cancel included
                    jTextArea2.append(mpv5.globals.Messages.MASSEXPORT_EMAIL_STARTED + " (" + mails.size() + ")\n");
                    new mpv5.utils.jobs.Job(new mpv5.utils.export.EmailBatch(mails), new mpv5.utils.jobs.Waiter() {
                        @Override
                        public void set(Object object, Exception exception) throws Exception {
                            if (exception != null) {
                                Popup.error(exception);
                            }
                        }
                    }, "Emails: " + mpv5.globals.Messages.DONE).execute();
                }
                showResults(createdItems, started);
                master.isEnd(true);
            });
        }
    }

    /**
     * The log with the created files as links: a click opens the file (or the
     * folder) with the program of the system
     */
    private void showResults(List<Item> items, long since) {
        java.util.LinkedHashSet<java.io.File> dirs = new java.util.LinkedHashSet<java.io.File>();
        for (Item i : items) {
            try {
                dirs.add(mpv5.db.objects.User.getSaveDir(i));
            } catch (Exception e) {
                mpv5.logging.Log.Debug(this, e);
            }
        }
        final List<java.io.File> files = new java.util.ArrayList<java.io.File>();
        for (java.io.File d : dirs) {
            java.io.File[] in = d.listFiles();
            if (in == null) {
                continue;
            }
            java.util.Arrays.sort(in);
            for (java.io.File f : in) {
                if (f.isFile() && f.lastModified() >= since) {
                    files.add(f);
                }
            }
        }
        final List<java.io.File> folders = new java.util.ArrayList<java.io.File>(dirs);
        StringBuilder h = new StringBuilder("<html><body style='font-family:sans-serif'>");
        h.append("<pre style='font-family:sans-serif'>").append(html(jTextArea2.getText())).append("</pre>");
        h.append("<p><b>").append(html(mpv5.globals.Messages.MASSEXPORT_FILES.toString())).append(" (").append(files.size()).append(")</b></p>");
        if (files.isEmpty()) {
            h.append("<p>").append(html(mpv5.globals.Messages.MASSEXPORT_NO_FILES.toString())).append("</p>");
        }
        for (int i = 0; i < files.size(); i++) {
            h.append("<p><a href='f:").append(i).append("'>").append(html(files.get(i).getName())).append("</a>")
                    .append(" &nbsp; <font color='#6b7280'>").append(html(files.get(i).getParent())).append("</font></p>");
        }
        for (int i = 0; i < folders.size(); i++) {
            h.append("<p><a href='d:").append(i).append("'>").append(html(mpv5.globals.Messages.MASSEXPORT_OPEN_FOLDER.toString()))
                    .append(": ").append(html(folders.get(i).getPath())).append("</a></p>");
        }
        h.append("</body></html>");
        javax.swing.JEditorPane pane = new javax.swing.JEditorPane("text/html", h.toString());
        pane.setEditable(false);
        pane.addHyperlinkListener(e -> {
            if (e.getEventType() != javax.swing.event.HyperlinkEvent.EventType.ACTIVATED || e.getDescription() == null) {
                return;
            }
            String ref = e.getDescription();
            try {
                int n = Integer.parseInt(ref.substring(2));
                mpv5.utils.files.FileDirectoryHandler.open(ref.startsWith("f:") ? files.get(n) : folders.get(n));
            } catch (Exception ex) {
                mpv5.logging.Log.Debug(this, ex);
            }
        });
        jScrollPane2.setViewportView(pane);
        //the list of files is what the user wants to see now
        javax.swing.SwingUtilities.invokeLater(() -> pane.scrollRectToVisible(new java.awt.Rectangle(0, pane.getHeight() - 1, 1, 1)));
    }

    private static String html(String s) {
        return s == null ? "" : s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    /**
     * Create and save the invoice of one contact: the positions of all its
     * selected documents, one after the other (the item panel's paste replaces
     * the record with a copy of each pasted document, so only the last one
     * ended up in the invoice). With PDF, e-invoice or email the invoice is
     * final: status "Finished". Opened in a tab as saved record.
     *
     * @return the saved invoice, null on failure
     */
    private Item createInvoice(Contact key, List<Item> value, boolean createEInvoice) {
        try {
            Date now = new Date();
            Item i = Item.createFor(key);
            i.setGroup((Group) Group.getObject(Context.getGroup(), Integer.valueOf(labeledCombobox1.getSelectedItem().getId())));
            i.setDatetodo(now);
            i.setDateend(now);
            //the account of the combined documents (required)
            int account = value.isEmpty() ? 0 : value.get(0).__getAccountsids();
            i.setAccountsids(account > 0 ? account : 1);
            boolean issued = jCheckBox1.isSelected() || createEInvoice || email.isSelected();
            i.setIntstatus(issued ? Item.STATUS_FINISHED : Item.STATUS_QUEUED);
            if (value.size() == 1 && value.get(0).__getInttype() == Item.TYPE_ORDER) {
                i.setReforderids(value.get(0).__getIDS());
            }
            if (!i.save(true)) {
                jTextArea2.append(String.format(mpv5.globals.Messages.MASSEXPORT_CREATED_FAILED.toString(), key) + "\n");
                return null;
            }
            int pos = 0;
            //like pasting into a document: summary lines (setting, default) or the positions
            boolean summary = mpv5.db.objects.User.pasteAsSummary();
            for (Item source : value) {
                SubItem[] lines = summary
                        ? mpv5.handler.ItemService.asPositions(source, mpv5.globals.Messages.GOOSE1 + " " + source.__getCnumber() + " "
                                + mpv5.globals.Messages.GOOSE2 + " " + mpv5.utils.date.DateConverter.getDefDateString(source.__getDateadded()))
                                .toArray(new SubItem[0])
                        : mpv5.handler.ItemService.copyPositions(source);
                for (SubItem s : lines) {
                    s.setItemsids(i.__getIDS());
                    s.setOrdernr(++pos);
                    s.setDateadded(now);
                    s.save(true);
                }
            }
            mpv5.handler.ItemService.updateTotals(i);
            //ZUGFeRD: the e-invoice is the PDF (same file name), no plain PDF
            boolean zugferd = createEInvoice && mpv5.utils.export.EInvoiceFiles.replacesPdf(key);
            if (jCheckBox1.isSelected() && !zugferd) {
                //toPdf only uses a loaded template (the item panel used to load it)
                if (mpv5.handler.TemplateHandler.loadTemplate(i) != null) {
                    i.toPdf(false);
                } else {
                    jTextArea2.append(i.__getCnumber() + ": " + mpv5.globals.Messages.NO_TEMPLATE_DEFINDED + "\n");
                }
            }
            jTextArea2.append(String.format(mpv5.globals.Messages.MASSEXPORT_CREATED.toString(),
                    Item.getTypeString(Item.TYPE_INVOICE) + " " + i.__getCnumber(), key.__getCname(),
                    mpv5.utils.numberformat.FormatNumber.formatLokalCurrency(i.getGrossAmount()), pos) + "\n");
            //summary lines: the documents are invoiced now (as when pasted)
            if (jCheckBox2.isSelected() || summary) {
                for (Item get : value) {
                    get.setIntstatus(Item.STATUS_FINISHED);
                    get.save(true);
                }
            }
            if (jCheckBox3.isSelected()) {
                //as stored: a saved record, not a "new" one
                mpv5.YabsViewProxy.instance().getIdentifierView().addTab(DatabaseObject.getObject(Context.getInvoice(), i.__getIDS()), true);
            }
            return i;
        } catch (Exception ex) {
            Logger.getLogger(wizard_MassExportPanel.class.getName()).log(Level.SEVERE, null, ex);
            jTextArea2.append(key + ": " + mpv5.globals.Messages.ERROR_OCCURED.toString().trim() + " " + ex.getLocalizedMessage() + "\n");
            return null;
        }
    }

    /**
     * @param indeterminate true: running animation (e.g. while an e-invoice
     * is checked)
     */
    private void progress(final javax.swing.JProgressBar bar, final int number, final int total, final String what,
            final boolean indeterminate) {
        onEdt(() -> {
            mpv5.ui.modern.Edt.setIndeterminate(bar, indeterminate);
            bar.setString(number + " / " + total + "  " + what);
        });
    }

    private void setControlsEnabled(boolean enabled) {
        for (javax.swing.JComponent c : new javax.swing.JComponent[]{jCheckBox1, jCheckBox2, jCheckBox3, einvoice, email, labeledCombobox1}) {
            c.setEnabled(enabled);
        }
    }

    /**
     * Run on the event dispatch thread and wait for it
     */
    private static void onEdt(Runnable r) {
        if (SwingUtilities.isEventDispatchThread()) {
            r.run();
            return;
        }
        try {
            SwingUtilities.invokeAndWait(r);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        } catch (java.lang.reflect.InvocationTargetException e) {
            Logger.getLogger(wizard_MassExportPanel.class.getName()).log(Level.SEVERE, null, e.getCause());
        }
    }

