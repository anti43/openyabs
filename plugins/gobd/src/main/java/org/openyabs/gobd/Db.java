package org.openyabs.gobd;

import java.io.Reader;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.sql.Types;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Locale;

/**
 * The database of YaBS for the GoBD tables: prepared statements, errors as
 * exceptions (never swallowed) and transactions. The query methods of YaBS
 * log and swallow errors; the plugin must not take a failed write for a lock
 * or a failed read for "not locked".
 */
final class Db {

    /**
     * Work in a transaction
     *
     * @param <T>
     */
    interface Work<T> {

        T run(Connection c) throws Exception;
    }

    private Db() {
    }

    /**
     * @return the connection of YaBS
     * @throws SQLException if there is none
     */
    static Connection connection() throws SQLException {
        mpv5.db.common.DatabaseConnection dc = mpv5.db.common.DatabaseConnection.getConnector();
        Connection c = dc == null ? null : dc.getConnection();
        if (c == null) {
            throw new SQLException("Keine Datenbankverbindung");
        }
        return c;
    }

    private static String product(Connection c) {
        try {
            DatabaseMetaData md = c == null ? null : c.getMetaData();
            String name = md == null ? null : md.getDatabaseProductName();
            return name == null ? "" : name.toLowerCase(Locale.ROOT);
        } catch (SQLException ignored) {
            return "";
        }
    }

    static boolean isDerby(Connection c) {
        return product(c).contains("derby");
    }

    static boolean isH2(Connection c) {
        return product(c).contains("h2");
    }

    static boolean isMysql(Connection c) {
        String p = product(c);
        return p.contains("mysql") || p.contains("mariadb");
    }

    /**
     * @return SQL type for unlimited text (CLOB on Derby, LONGTEXT on MySQL/MariaDB, TEXT on H2/PostgreSQL)
     */
    static String largeTextType(Connection c) {
        if (isDerby(c)) {
            return "CLOB";
        }
        if (isMysql(c)) {
            return "LONGTEXT";
        }
        return "TEXT";
    }

    /**
     * @return SQL definition for an auto-increment BIGINT primary key
     */
    static String identityPrimaryKey(Connection c) {
        if (isMysql(c)) {
            return "BIGINT AUTO_INCREMENT PRIMARY KEY";
        }
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    }

    /**
     * @return SQL suffix that limits a SELECT to one row
     */
    static String limitOne(Connection c) {
        if (isMysql(c)) {
            return " LIMIT 1";
        }
        return " FETCH FIRST 1 ROWS ONLY";
    }

    /**
     * Creates a table if it does not exist yet (works on Derby, H2, PostgreSQL and MySQL).
     */
    static void createTableIfMissing(Connection c, String table, String ddl) throws SQLException {
        synchronized (c) {
            try (PreparedStatement ps = c.prepareStatement("SELECT 1 FROM " + table + " WHERE 1 = 0");
                    ResultSet rs = ps.executeQuery()) {
                return;
            } catch (SQLException missing) {
                // table does not exist yet
            }
            try {
                update(c, ddl);
            } catch (SQLException e) {
                if (!isAlreadyExists(e)) {
                    throw e;
                }
            }
        }
    }

    /**
     * Adds a column if it does not exist yet (works on Derby, H2, PostgreSQL and MySQL).
     */
    static void addColumnIfMissing(Connection c, String table, String column, String columnDef) throws SQLException {
        synchronized (c) {
            try (PreparedStatement ps = c.prepareStatement("SELECT " + column + " FROM " + table + " WHERE 1 = 0");
                    ResultSet rs = ps.executeQuery()) {
                return;
            } catch (SQLException missing) {
                // column does not exist yet
            }
            try {
                update(c, "ALTER TABLE " + table + " ADD COLUMN " + column + " " + columnDef);
            } catch (SQLException e) {
                if (!isAlreadyExists(e)) {
                    throw e;
                }
            }
        }
    }

    /**
     * Creates a unique index if it does not exist yet (works on Derby, H2, PostgreSQL and MySQL).
     */
    static void createUniqueIndexIfMissing(Connection c, String indexName, String table, String column) throws SQLException {
        synchronized (c) {
            if (indexExists(c, table, indexName)) {
                return;
            }
            try {
                update(c, "CREATE UNIQUE INDEX " + indexName + " ON " + table + " (" + column + ")");
            } catch (SQLException e) {
                if (!isAlreadyExists(e)) {
                    throw e;
                }
            }
        }
    }

    /**
     * Adds a unique constraint allowing multiple NULL values if it does not exist yet.
     * H2 in MODE=Derby requires {@code UNIQUE NULLS DISTINCT}; Derby, PostgreSQL and MySQL
     * allow multiple NULLs in standard {@code UNIQUE (col)} constraints.
     */
    static void addUniqueConstraintIfMissing(Connection c, String table, String constraintName, String column) throws SQLException {
        synchronized (c) {
            String sql = isH2(c)
                    ? "ALTER TABLE " + table + " ADD CONSTRAINT IF NOT EXISTS " + constraintName + " UNIQUE NULLS DISTINCT (" + column + ")"
                    : "ALTER TABLE " + table + " ADD CONSTRAINT " + constraintName + " UNIQUE (" + column + ")";
            try {
                update(c, sql);
            } catch (SQLException e) {
                if (!isAlreadyExists(e)) {
                    throw e;
                }
            }
        }
    }

    private static boolean indexExists(Connection c, String table, String indexName) {
        try {
            DatabaseMetaData md = c.getMetaData();
            String t = md.storesUpperCaseIdentifiers() ? table.toUpperCase(Locale.ROOT)
                    : md.storesLowerCaseIdentifiers() ? table.toLowerCase(Locale.ROOT) : table;
            String catalog = isMysql(c) ? c.getCatalog() : null;
            try (ResultSet rs = md.getIndexInfo(catalog, null, t, false, false)) {
                while (rs.next()) {
                    String name = rs.getString("INDEX_NAME");
                    if (name != null && name.equalsIgnoreCase(indexName)) {
                        return true;
                    }
                }
            }
        } catch (SQLException ignored) {
            // fall back to CREATE INDEX + isAlreadyExists
        }
        return false;
    }

    static boolean isAlreadyExists(SQLException e) {
        for (SQLException cur = e; cur != null; cur = cur.getNextException()) {
            String state = cur.getSQLState();
            if ("X0Y32".equals(state) || "42S01".equals(state) || "42S11".equals(state)
                    || "42S21".equals(state) || "42P07".equals(state) || "42701".equals(state)
                    || "42710".equals(state) || "90045".equals(state) || "Z0001".equals(state)) {
                return true;
            }
            int code = cur.getErrorCode();
            if (code == 1050 || code == 1060 || code == 1061) {
                return true;
            }
        }
        return false;
    }

    /**
     * @param c
     * @param sql with ? for the parameters
     * @param params
     * @return the rows (CLOBs as text)
     * @throws SQLException
     */
    static Object[][] query(Connection c, String sql, Object... params) throws SQLException {
        synchronized (c) {
            try (PreparedStatement ps = c.prepareStatement(sql)) {
                bind(ps, params);
                try (ResultSet rs = ps.executeQuery()) {
                    int n = rs.getMetaData().getColumnCount();
                    List<Object[]> rows = new ArrayList<Object[]>();
                    while (rs.next()) {
                        Object[] row = new Object[n];
                        for (int i = 0; i < n; i++) {
                            row[i] = value(rs.getObject(i + 1));
                        }
                        rows.add(row);
                    }
                    return rows.toArray(new Object[0][]);
                }
            }
        }
    }

    /**
     * @return the first row, null if none
     */
    static Object[] first(Connection c, String sql, Object... params) throws SQLException {
        Object[][] r = query(c, sql, params);
        return r.length > 0 ? r[0] : null;
    }

    /**
     * @param c
     * @param sql with ? for the parameters
     * @param params
     * @return the number of changed rows
     * @throws SQLException
     */
    static int update(Connection c, String sql, Object... params) throws SQLException {
        synchronized (c) {
            try (PreparedStatement ps = c.prepareStatement(sql)) {
                bind(ps, params);
                return ps.executeUpdate();
            }
        }
    }

    /**
     * Runs the work in a transaction: commit if it returns, rollback if it
     * throws. Inside a running transaction it is part of that one. The
     * connection is the one of YaBS: the transaction runs on the Swing thread
     * (as the queries of YaBS), so no other query of YaBS ends up in it.
     *
     * @param <T>
     * @param work
     * @return what the work returns
     * @throws Exception what the work throws
     */
    static <T> T tx(Work<T> work) throws Exception {
        if (!java.awt.EventQueue.isDispatchThread()) {
            Object[] result = new Object[1];
            Exception[] failure = new Exception[1];
            java.awt.EventQueue.invokeAndWait(() -> {
                try {
                    result[0] = tx(work);
                } catch (Exception e) {
                    failure[0] = e;
                }
            });
            if (failure[0] != null) {
                throw failure[0];
            }
            @SuppressWarnings("unchecked")
            T t = (T) result[0];
            return t;
        }
        Connection c = connection();
        synchronized (c) {
            if (!c.getAutoCommit()) {
                return work.run(c);
            }
            c.setAutoCommit(false);
            try {
                T result = work.run(c);
                c.commit();
                return result;
            } catch (Exception | Error e) {
                try {
                    c.rollback();
                } catch (SQLException rollbackFailed) {
                    e.addSuppressed(rollbackFailed);
                }
                throw e;
            } finally {
                c.setAutoCommit(true);
            }
        }
    }

    /**
     * @param e
     * @return true for a violated unique key (another client was faster)
     */
    static boolean isUniqueViolation(Throwable e) {
        for (Throwable t = e; t != null; t = t.getCause()) {
            if (t instanceof SQLException) {
                SQLException se = (SQLException) t;
                if ("23505".equals(se.getSQLState())
                        || ("23000".equals(se.getSQLState()) && se.getErrorCode() == 1062)) {
                    return true;
                }
            }
        }
        return false;
    }

    private static void bind(PreparedStatement ps, Object... params) throws SQLException {
        for (int i = 0; i < params.length; i++) {
            Object p = params[i];
            if (p == null) {
                int sqlType = Types.NULL;
                try {
                    sqlType = ps.getParameterMetaData().getParameterType(i + 1);
                } catch (SQLException ignored) {
                    // driver without parameter metadata (e.g. MySQL client-side prepared statements)
                }
                if (sqlType == Types.NULL || sqlType == Types.OTHER) {
                    ps.setObject(i + 1, null);
                } else {
                    ps.setNull(i + 1, sqlType);
                }
            } else {
                if (p instanceof Date && !(p instanceof java.sql.Date) && !(p instanceof Timestamp)) {
                    p = new Timestamp(((Date) p).getTime());
                }
                ps.setObject(i + 1, p);
            }
        }
    }

    private static Object value(Object o) throws SQLException {
        if (o instanceof Clob) {
            Clob clob = (Clob) o;
            try (Reader r = clob.getCharacterStream()) {
                StringBuilder b = new StringBuilder();
                char[] buf = new char[8192];
                int n;
                while ((n = r.read(buf)) > 0) {
                    b.append(buf, 0, n);
                }
                return b.toString();
            } catch (java.io.IOException e) {
                throw new SQLException(e);
            }
        }
        return o;
    }
}
